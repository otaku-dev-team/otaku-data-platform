-- 阶段 1 契约 §2.1：详情接口新增可空的 source_url（来源站人读原页地址）
--
-- 为什么落库而不是运行时拼：
-- 1. 契约明确「无法可靠确定时返回 null，不能通过猜测生成」——后端不做推导；
-- 2. 不同来源的 URL 规则由各自适配器维护（§4.7），后端不该硬编码；
-- 3. 多来源并存后，后端没有任何通用办法从 source + source_id 反推出原页地址。
--
-- 兼容性：可空、不带默认值，历史行为空；列表接口不返回该字段（仍 6 字段）。

ALTER TABLE work
    ADD COLUMN source_url VARCHAR(1024) NULL
        COMMENT '来源站人读原页地址，由适配器提供；仅供详情回跳，不参与唯一标识'
        AFTER source_id;
